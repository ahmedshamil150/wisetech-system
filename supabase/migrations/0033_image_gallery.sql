-- Image gallery: batch photo documentation for ultrasound equipment.
--
-- Each physical batch of items gets a sequential group code (1U, 2U, ...)
-- written on the machine with a marker. Photos of the machine, its printer
-- and its probes are uploaded to Cloudflare R2 and metadata is stored here.
-- The group code is then written back to machines/probes/printers via the
-- nullable image_group_code column so inventory items link to their photos.

create table if not exists public.image_groups (
  id bigint generated by default as identity primary key,
  group_code text not null,
  batch_name text not null,
  created_at timestamptz not null default now(),
  unique (batch_name, group_code)
);

create table if not exists public.item_images (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.image_groups(id) on delete cascade,
  item_type text not null check (item_type in ('machine', 'printer', 'probe')),
  item_serial text,
  item_model text,
  r2_key text not null,
  r2_url text not null,
  uploaded_at timestamptz not null default now()
);

create index if not exists item_images_group_id_idx on public.item_images(group_id);
create index if not exists image_groups_batch_name_idx on public.image_groups(batch_name);

-- Nullable link from inventory items to their photo group.
alter table public.machines
  add column if not exists image_group_code text;
alter table public.probes
  add column if not exists image_group_code text;
alter table public.printers
  add column if not exists image_group_code text;

create index if not exists machines_image_group_code_idx on public.machines(image_group_code);
create index if not exists probes_image_group_code_idx on public.probes(image_group_code);
create index if not exists printers_image_group_code_idx on public.printers(image_group_code);

-- RLS: gallery data is readable by all authenticated members, writable by admins.
alter table public.image_groups enable row level security;
alter table public.item_images enable row level security;

create policy if not exists image_groups_select
  on public.image_groups for select
  to authenticated
  using (true);
create policy if not exists image_groups_insert
  on public.image_groups for insert
  to authenticated
  with check (true);
create policy if not exists image_groups_update
  on public.image_groups for update
  to authenticated
  using (true);
create policy if not exists image_groups_delete
  on public.image_groups for delete
  to authenticated
  using (true);

create policy if not exists item_images_select
  on public.item_images for select
  to authenticated
  using (true);
create policy if not exists item_images_insert
  on public.item_images for insert
  to authenticated
  with check (true);
create policy if not exists item_images_update
  on public.item_images for update
  to authenticated
  using (true);
create policy if not exists item_images_delete
  on public.item_images for delete
  to authenticated
  using (true);
